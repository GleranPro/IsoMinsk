/** OSM URL for an id in the catalog form (`w123`, `n123`, `r123`). */
export function osmObjectUrl(osm: string): string {
  const kind = osm.startsWith('n') ? 'node' : osm.startsWith('r') ? 'relation' : 'way';
  return `https://www.openstreetmap.org/${kind}/${osm.slice(1)}`;
}
